/**
 * Runs the real seed (including ledger postings through the engine) against an
 * in-process Postgres (PGlite), then exports every seeded row EXCEPT hs_codes as
 * one SQL script. Used to seed a hosted database through a SQL console when no
 * DATABASE_URL is available locally.
 *   npx tsx scripts/export-seed-sql.ts > supabase/seed.sql
 * The file has no BEGIN/COMMIT so it can run inside a DO block or a SQL editor
 * transaction; run it as ONE transaction (the ledger balance trigger is deferred
 * to commit). Accounts, FX rates and HS codes are loaded separately/idempotently.
 */
import { createTestDb } from '../test/pglite'
import { seed } from '../src/db/seed'

const TABLES = [
  'accounts',
  'fx_rates',
  'shipments',
  'documents',
  'line_items',
  'invoices',
  'ledger_transactions',
  'ledger_entries',
  'escrow_milestones',
  'payouts',
  'idempotency_keys',
  'audit_log',
]

async function main() {
  const t = await createTestDb()
  await seed(t.db)

  const out: string[] = ['-- NexusTrade demo data, generated by scripts/export-seed-sql.ts from the real seed. Fictitious companies and TRNs.', '-- Run as ONE transaction. Safe to re-run (ON CONFLICT DO NOTHING).']
  for (const table of TABLES) {
    const { rows } = await t.pg.query<{ json: string | null }>(`SELECT json_agg(t)::text AS json FROM ${table} t`)
    const json = rows[0]?.json
    if (!json) continue
    if (json.includes('$seed$')) throw new Error('delimiter clash')
    out.push(`INSERT INTO public.${table} SELECT * FROM json_populate_recordset(null::public.${table}, $seed$${json}$seed$) ON CONFLICT DO NOTHING;`)
  }
  process.stdout.write(out.join('\n') + '\n')
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
